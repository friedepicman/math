def download_pdf(url, filepath):
    if os.path.exists(filepath):
        print(f"  Skip: {os.path.basename(filepath)}")
        return True
    try:
        r = requests.get(url, headers={'User-Agent': 'Mozilla/5.0'}, timeout=30, allow_redirects=True)
        if r.status_code == 200 and (r.content[:4] == b'%PDF' or 'pdf' in r.headers.get('Content-Type', '')):
            with open(filepath, 'wb') as f: f.write(r.content)
            print(f"  OK: {os.path.basename(filepath)} ({len(r.content)} bytes)")
            return True
        print(f"  FAIL ({r.status_code}): {os.path.basename(filepath)}")
    except Exception as e:
        print(f"  ERR: {e}")
    return False

def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    entries = [(y, d, r, t, f"{BASE_URL}{l}", f"PUMaC_{y}_{r}{'_'+d if d else ''}_{t}.pdf", l) 
               for l, y, d, r, t in PDF_LINKS]
    entries.sort(key=lambda x: (-x[0], x[2], x[1], x[3]))
    
    print(f"PUMaC Scraper: {len(entries)} PDFs, years {min(e[0] for e in entries)}-{max(e[0] for e in entries)}")
    
    ok = fail = 0
    for i, (yr, div, rnd, typ, url, fn, _) in enumerate(entries, 1):
        print(f"[{i}/{len(entries)}] {yr} {rnd}{' Div '+div if div else ''} {typ}")
        if download_pdf(url, os.path.join(OUTPUT_DIR, fn)): ok += 1
        else: fail += 1
        time.sleep(random.uniform(0.5, 1.5))
    
    with open(os.path.join(OUTPUT_DIR, "manifest.csv"), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['competition','year','round','division','type','filename','url'])
        for yr, div, rnd, typ, url, fn, _ in entries:
            w.writerow(['PUMaC', yr, rnd, div, typ, fn, url])
    
    print(f"\nDone! OK:{ok} FAIL:{fail} -> {OUTPUT_DIR}/")

if __name__ == "__main__":
    main()